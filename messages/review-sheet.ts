// Builds docs/i18n/es-review.md, the sheet a native speaker checks: every message a
// translation marks as needing native review (its `needsReview` list), with the English,
// the translation and where it shows. messages/i18n.test.ts keeps the file current.
import type { Messages } from '@solara/core/i18n'

/** Where each namespace's text shows, for the reviewer. */
const CONTEXT: Record<string, string> = {
  core: 'UV categories, rain and heat, forecast confidence (dashboard, alerts, calendar feed)',
  briefing: 'The daily briefing at the top of the dashboard, and shared briefings',
  sunscreen: 'Sunscreen coaching: the timer, activity cards, Settings; the reapply reminder push',
  skinQuiz: 'The Fitzpatrick skin type questionnaire (setup and Settings)',
  dashboard: 'The dashboard: burn time and vitamin D cards, calendar event text',
  settings: 'Settings',
  setup: 'Setup and the skin type step',
  activities: 'Activity cards, the hero slot and the activity editor',
  events: 'Imported events and their UV',
}

/** A message with its parameters shown as {1}, {2}, ... (a list as one value). */
function show(message: Messages[string]): string {
  if (typeof message === 'string') return message
  const names = Array.from({ length: message.length }, (_, i) => `{${i + 1}}`)
  try {
    return message(...names)
  } catch {
    return message(...names.map(name => [name]))
  }
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replaceAll('\n', ' ').replaceAll('\u00a0', ' ')
}

export function reviewSheet(
  sources: ReadonlyMap<string, Readonly<Messages>>,
  translations: Readonly<Record<string, Messages>>,
  modules: Record<string, { default?: unknown; needsReview?: string[] }>,
): string {
  const lines = [
    '# Spanish safety wording: native review',
    '',
    '<!-- Generated by messages/review-sheet.ts; messages/i18n.test.ts checks it. Do not edit by hand: change the catalogue and run UPDATE_I18N_REVIEW=1 npx vitest run messages. -->',
    '',
    'These Spanish messages give health and safety guidance: burn times, SPF advice, seeking shade, UV categories and sunscreen amounts.',
    'A machine or a non-native speaker wrote the first draft, so a native speaker of Latin American Spanish checks each one before release ([ROADMAP item 46](../ROADMAP.md#46-languages-setup-and-the-app-in-spanish-built)).',
    'UV categories follow the WHO and PAHO Spanish terms (Bajo, Moderado, Alto, Muy alto, Extremo).',
    'Values such as times, UV readings and names appear as {1}, {2} and so on.',
    '',
    'How to review: for each row, check that the Spanish says the same thing as the English, in plain and friendly neutral Latin American Spanish with "tú".',
    'Write corrections in the Notes column (or send them to the owner); once a row is right, its key comes off the `needsReview` list in the Spanish catalogue and leaves this sheet.',
    '',
  ]
  let total = 0
  for (const spanishModule of Object.values(modules)) {
    if (!spanishModule.needsReview?.length) continue
    const entry = Object.entries(translations).find(([, t]) => t === spanishModule.default)
    if (!entry) continue
    const [namespace, translation] = entry
    const source = sources.get(namespace)
    if (!source) continue
    lines.push(`## ${namespace}`, '', CONTEXT[namespace] ?? namespace, '')
    lines.push('| Key | English | Spanish | Notes |', '| --- | --- | --- | --- |')
    for (const key of spanishModule.needsReview) {
      lines.push(
        `| \`${key}\` | ${cell(show(source[key]!))} | ${cell(show(translation[key]!))} |  |`,
      )
      total += 1
    }
    lines.push('')
  }
  lines.push(`${total} messages to review.`, '')
  return lines.join('\n')
}
